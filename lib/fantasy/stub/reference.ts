function p(
  n: number,
  year: number,
  fullName: string,
  displayName: string,
  position: Position,
  priceTenths: number,
  totalPoints: number,
  selectedByPct: number,
): Player {
  return {
    id: uuid("1", n),
    teamId: uuid("7", year),
    teamShort: `Y${year}`,
    teamYear: year,
    fullName,
    displayName,
    position,
    priceTenths,
    status: n % 37 === 0 ? "injured" : n % 53 === 0 ? "suspended" : "available",
    shirtNumber: (n % 30) + 1,
    totalPoints,
    selectedByPct,
  };
}

